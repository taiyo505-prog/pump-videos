function kindOf(r) {
  var n = r.name.replace(/フライパン/g, 'パン'), s = r.steps.join('').replace(/フライパン/g, 'パン');
  if (r.cat === 'デザート') return /焼|オーブン|トースター/.test(s) ? ['bake', 'dessert'] : ['dessert'];
  if (/鍋(?!肉)|ポトフ|チゲ/.test(n)) return ['nabe', 'soup'];
  if (r.cat === '汁物') return ['soup'];
  if (/チャーハン|炒飯|ピラフ/.test(n)) return ['rice', 'stir'];
  if (/丼|ライス/.test(n)) return ['don', /揚げ/.test(s) ? 'fry' : /煮/.test(s) ? 'simmer' : 'stir'];
  if (/パスタ|スパゲッティ|ナポリタン|カルボナーラ|ペペロンチーノ|ボンゴレ/.test(n)) return ['pasta'];
  if (/うどん|そば|ラーメン|麺|そうめん/.test(n)) return ['noodle'];
  if (/揚げ焼き|揚げ|フライ|天ぷら|から揚げ|唐揚げ|カツ/.test(n + s) && !/揚げびたし|厚揚げ|油揚げ/.test(n)) return ['fry'];
  if (/卵焼き|だし巻き|オムレツ|卵炒め|ニラ玉|かに玉|しりしり/.test(n)) return ['egg', 'stir'];
  if (/煮|肉じゃが|筑前/.test(n) || /落としぶた|煮る/.test(s)) return ['simmer'];
  if (/サラダ|マリネ|カルパッチョ|コールスロー/.test(n)) return ['salad'];
  if (/漬け|酢の物|浅漬け|なます/.test(n)) return ['pickle'];
  if (/ナムル|おひたし|あえ|和え/.test(n)) return ['boil'];
  if (/グラタン|ドリア|ピザ|トースト|チーズ焼き|オーブン/.test(n + s)) return ['bake'];
  if (/蒸し|レンジ/.test(n)) return ['steam'];
  if (/焼き|ステーキ|ソテー|ムニエル|照り焼き|ハンバーグ|つくね/.test(n)) return ['grill'];
  if (/炒め/.test(n + s)) return ['stir'];
  return ['stir'];
}
